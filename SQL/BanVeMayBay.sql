CREATE DATABASE IF NOT EXISTS BanVeMayBay
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE BanVeMayBay;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS ChiTietHoaDon;
DROP TABLE IF EXISTS Ve;
DROP TABLE IF EXISTS HoaDon;
DROP TABLE IF EXISTS DatVe;
DROP TABLE IF EXISTS Ghe;
DROP TABLE IF EXISTS ChuyenBay;
DROP TABLE IF EXISTS Voucher;
DROP TABLE IF EXISTS MayBay;
DROP TABLE IF EXISTS HanhKhach;
DROP TABLE IF EXISTS HangVe;
DROP TABLE IF EXISTS CTKM;
DROP TABLE IF EXISTS KhachHang;
DROP TABLE IF EXISTS NhanVien;
DROP TABLE IF EXISTS SanBay;
DROP TABLE IF EXISTS HangHangKhong;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE HangHangKhong (
  MaHHK   VARCHAR(10)  NOT NULL,
  TenHang VARCHAR(100) NOT NULL,
  PRIMARY KEY (MaHHK)
) ENGINE=InnoDB;

CREATE TABLE SanBay (
  MaSanBay   VARCHAR(10)  NOT NULL,
  Ten        VARCHAR(100) NOT NULL,
  LoaiSanBay VARCHAR(50)  NULL,
  PRIMARY KEY (MaSanBay)
) ENGINE=InnoDB;

CREATE TABLE NhanVien (
  MaNV   VARCHAR(10) NOT NULL,
  Ho     VARCHAR(50) NOT NULL,
  Ten    VARCHAR(50) NOT NULL,
  ChucVu VARCHAR(50) NULL,
  PRIMARY KEY (MaNV)
) ENGINE=InnoDB;

CREATE TABLE KhachHang (
  MaKH     VARCHAR(10)  NOT NULL,
  HoTen    VARCHAR(100) NOT NULL,
  CCCD     VARCHAR(12)  NOT NULL,
  SDT      VARCHAR(15)  NULL,
  Email    VARCHAR(100) NULL,
  TaiKhoan VARCHAR(50)  NOT NULL,
  MatKhau  VARCHAR(255) NOT NULL,
  DiaChi   VARCHAR(200) NULL,
  PRIMARY KEY (MaKH),
  UNIQUE KEY UQ_KhachHang_CCCD (CCCD),
  UNIQUE KEY UQ_KhachHang_TaiKhoan (TaiKhoan)
) ENGINE=InnoDB;

CREATE TABLE HangVe (
  MaHV     VARCHAR(10)  NOT NULL,
  TenHV    VARCHAR(50)  NOT NULL,
  HanhLyKg INT          NOT NULL,
  DonGiaVe DECIMAL(18,0) NOT NULL,
  PRIMARY KEY (MaHV),
  CONSTRAINT CK_HangVe_HanhLyKg CHECK (HanhLyKg >= 0),
  CONSTRAINT CK_HangVe_DonGiaVe CHECK (DonGiaVe >= 0)
) ENGINE=InnoDB;

CREATE TABLE CTKM (
  MaCTKM      VARCHAR(10)  NOT NULL,
  TenCTKM     VARCHAR(100) NOT NULL,
  NgayBatDau  DATE         NOT NULL,
  NgayKetThuc DATE         NOT NULL,
  PRIMARY KEY (MaCTKM),
  CONSTRAINT CK_CTKM_Ngay CHECK (NgayKetThuc >= NgayBatDau)
) ENGINE=InnoDB;

CREATE TABLE MayBay (
  MaMayBay VARCHAR(10) NOT NULL,
  MaHHK    VARCHAR(10) NOT NULL,
  PRIMARY KEY (MaMayBay),
  CONSTRAINT FK_MayBay_HHK FOREIGN KEY (MaHHK) REFERENCES HangHangKhong (MaHHK)
) ENGINE=InnoDB;

CREATE TABLE HanhKhach (
  MaHK     VARCHAR(10)  NOT NULL,
  HoTen    VARCHAR(100) NOT NULL,
  NgaySinh DATE         NULL,
  CCCD     VARCHAR(12)  NULL,
  GioiTinh VARCHAR(10)  NULL,
  MaKH     VARCHAR(10)  NOT NULL,
  LoaiHK   VARCHAR(30)  NULL,
  PRIMARY KEY (MaHK),
  CONSTRAINT FK_HK_KH FOREIGN KEY (MaKH) REFERENCES KhachHang (MaKH)
) ENGINE=InnoDB;

CREATE TABLE Voucher (
  MaVoucher VARCHAR(20)    NOT NULL,
  MaCTKM    VARCHAR(10)    NOT NULL,
  GiamGia   DECIMAL(18,2)  NOT NULL,
  PRIMARY KEY (MaVoucher),
  CONSTRAINT FK_Voucher_CTKM FOREIGN KEY (MaCTKM) REFERENCES CTKM (MaCTKM),
  CONSTRAINT CK_Voucher_GiamGia CHECK (GiamGia >= 0)
) ENGINE=InnoDB;

CREATE TABLE ChuyenBay (
  MaChuyenBay   VARCHAR(10)    NOT NULL,
  MaHHK         VARCHAR(10)    NOT NULL,
  MaSanBayDi    VARCHAR(10)    NOT NULL,
  MaSanBayDen   VARCHAR(10)    NOT NULL,
  MaMayBay      VARCHAR(10)    NOT NULL,
  NgayKhoiHanh  DATETIME       NOT NULL,
  NgayDen       DATETIME       NOT NULL,
  ThoiGianBay   INT            NULL,
  ThoiGianDen   TIME           NULL,
  TongSoGhe     INT            NOT NULL,
  SoVeDaBan     INT            NOT NULL DEFAULT 0,
  GiaVe         DECIMAL(18,0)  NOT NULL,
  TrangThai     VARCHAR(30)    NOT NULL DEFAULT 'Chưa khởi hành',
  PRIMARY KEY (MaChuyenBay),
  CONSTRAINT FK_CB_HHK FOREIGN KEY (MaHHK) REFERENCES HangHangKhong (MaHHK),
  CONSTRAINT FK_CB_MayBay FOREIGN KEY (MaMayBay) REFERENCES MayBay (MaMayBay),
  CONSTRAINT FK_CB_SBDi FOREIGN KEY (MaSanBayDi) REFERENCES SanBay (MaSanBay),
  CONSTRAINT FK_CB_SBDen FOREIGN KEY (MaSanBayDen) REFERENCES SanBay (MaSanBay),
  CONSTRAINT CK_CB_Ngay CHECK (NgayDen >= NgayKhoiHanh),
  CONSTRAINT CK_CB_SanBay CHECK (MaSanBayDi <> MaSanBayDen),
  CONSTRAINT CK_CB_GiaVe CHECK (GiaVe >= 0),
  CONSTRAINT CK_CB_TongSoGhe CHECK (TongSoGhe >= 0),
  CONSTRAINT CK_CB_SoVeDaBan CHECK (SoVeDaBan >= 0),
  CONSTRAINT CK_CB_SoVe CHECK (SoVeDaBan <= TongSoGhe)
) ENGINE=InnoDB;

CREATE TABLE Ghe (
  MaGhe    VARCHAR(10) NOT NULL,
  MaMayBay VARCHAR(10) NOT NULL,
  MaHV     VARCHAR(10) NOT NULL,
  PRIMARY KEY (MaGhe),
  CONSTRAINT FK_Ghe_MayBay FOREIGN KEY (MaMayBay) REFERENCES MayBay (MaMayBay),
  CONSTRAINT FK_Ghe_HangVe FOREIGN KEY (MaHV) REFERENCES HangVe (MaHV)
) ENGINE=InnoDB;

CREATE TABLE DatVe (
  MaDV        VARCHAR(10)    NOT NULL,
  MaKH        VARCHAR(10)    NOT NULL,
  MaNV        VARCHAR(10)    NULL,
  MaChuyenBay VARCHAR(10)    NOT NULL,
  NgayDat     DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TongTien    DECIMAL(18,0)  NOT NULL DEFAULT 0,
  GiamGia     DECIMAL(18,2)  NOT NULL DEFAULT 0,
  TrangThai   VARCHAR(30)    NOT NULL DEFAULT 'Chờ thanh toán',
  MaVoucher   VARCHAR(20)    NULL,
  PRIMARY KEY (MaDV),
  UNIQUE KEY UQ_DatVe_MaDV_MaChuyenBay (MaDV, MaChuyenBay),
  CONSTRAINT FK_DV_KH FOREIGN KEY (MaKH) REFERENCES KhachHang (MaKH),
  CONSTRAINT FK_DV_NV FOREIGN KEY (MaNV) REFERENCES NhanVien (MaNV),
  CONSTRAINT FK_DV_CB FOREIGN KEY (MaChuyenBay) REFERENCES ChuyenBay (MaChuyenBay),
  CONSTRAINT FK_DV_Voucher FOREIGN KEY (MaVoucher) REFERENCES Voucher (MaVoucher)
) ENGINE=InnoDB;

CREATE TABLE HoaDon (
  MaHD         VARCHAR(10)    NOT NULL,
  MaKH         VARCHAR(10)    NOT NULL,
  MaNV         VARCHAR(10)    NULL,
  MaDV         VARCHAR(10)    NOT NULL,
  NgayLap      DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TongTien     DECIMAL(18,0)  NOT NULL DEFAULT 0,
  PhuongThucTT VARCHAR(30)    NULL,
  TrangThai    VARCHAR(30)    NOT NULL DEFAULT 'Chưa thanh toán',
  PRIMARY KEY (MaHD),
  CONSTRAINT FK_HD_KH FOREIGN KEY (MaKH) REFERENCES KhachHang (MaKH),
  CONSTRAINT FK_HD_NV FOREIGN KEY (MaNV) REFERENCES NhanVien (MaNV),
  CONSTRAINT FK_HD_DV FOREIGN KEY (MaDV) REFERENCES DatVe (MaDV)
) ENGINE=InnoDB;

CREATE TABLE Ve (
  MaVe        VARCHAR(10)    NOT NULL,
  MaChuyenBay VARCHAR(10)    NOT NULL,
  MaHV        VARCHAR(10)    NOT NULL,
  MaGhe       VARCHAR(10)    NOT NULL,
  MaHK        VARCHAR(10)    NOT NULL,
  DonGiaVe    DECIMAL(18,0)  NOT NULL,
  Ngay        DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MaDV        VARCHAR(10)    NULL,
  PRIMARY KEY (MaVe),
  UNIQUE KEY UQ_Ve_Chuyen_Ghe (MaChuyenBay, MaGhe),
  KEY IX_Ve_MaDV (MaDV),
  CONSTRAINT FK_Ve_CB FOREIGN KEY (MaChuyenBay) REFERENCES ChuyenBay (MaChuyenBay),
  CONSTRAINT FK_Ve_HV FOREIGN KEY (MaHV) REFERENCES HangVe (MaHV),
  CONSTRAINT FK_Ve_Ghe FOREIGN KEY (MaGhe) REFERENCES Ghe (MaGhe),
  CONSTRAINT FK_Ve_HK FOREIGN KEY (MaHK) REFERENCES HanhKhach (MaHK),
  CONSTRAINT FK_Ve_DatVe FOREIGN KEY (MaDV, MaChuyenBay) REFERENCES DatVe (MaDV, MaChuyenBay),
  CONSTRAINT CK_Ve_DonGiaVe CHECK (DonGiaVe >= 0)
) ENGINE=InnoDB;

CREATE TABLE ChiTietHoaDon (
  MaHD     VARCHAR(10)    NOT NULL,
  MaVe     VARCHAR(10)    NOT NULL,
  DonGiaVe DECIMAL(18,0)  NOT NULL,
  SL       INT            NOT NULL DEFAULT 1,
  ThanhTien DECIMAL(18,0) AS (SL * DonGiaVe) STORED,
  PRIMARY KEY (MaHD, MaVe),
  KEY IX_CTHD_MaVe (MaVe),
  CONSTRAINT FK_ChiTietHoaDon_HoaDon FOREIGN KEY (MaHD) REFERENCES HoaDon (MaHD),
  CONSTRAINT FK_ChiTietHoaDon_Ve FOREIGN KEY (MaVe) REFERENCES Ve (MaVe),
  CONSTRAINT CK_ChiTietHoaDon_SL CHECK (SL > 0),
  CONSTRAINT CK_ChiTietHoaDon_DonGiaVe CHECK (DonGiaVe >= 0)
) ENGINE=InnoDB;
